"""Local-only, in-memory UI verification server. Never contacts Supabase or AI.

Responses are generated by the real backend analysis/report builder. Only fake auth
accepts POST; product writes are rejected. Intended for manual F4 inspection at :3101.
"""
import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse

from generate_early_finish_reports import generate

DATA = generate()
USER = {
    "id": "11111111-1111-4111-8111-111111111111", "aud": "authenticated", "role": "authenticated",
    "email": "isolated@example.invalid", "app_metadata": {"provider": "email", "providers": ["email"]},
    "user_metadata": {}, "identities": [], "created_at": "2026-10-26T05:30:00Z",
}
PROFILE = {
    "id": "22222222-2222-4222-8222-222222222222", "age_range": "25-34",
    "usual_sleep_hours": 8, "usual_sleep_schedule": {"bedtime": "23:30", "wake_time": "07:30"},
    "activity_level": "lightly_active", "goals": ["Better focus"], "regular_habits": [], "constraints": [],
    "created_at": "2026-10-26T05:30:00Z", "updated_at": "2026-10-26T05:30:00Z",
}
TIMELINES = {item["report"]["experiment"]["id"]: item["timeline"] for item in DATA["cases"]}
REPORTS = {item["report"]["experiment"]["id"]: item["report"] for item in DATA["cases"]}


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *_args):
        pass  # Never print request bodies or auth headers.

    def reply(self, status, data):
        body = json.dumps(data).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "http://localhost:3101")
        self.send_header("Access-Control-Allow-Headers", "authorization,apikey,content-type,x-client-info,x-supabase-api-version")
        self.send_header("Access-Control-Allow-Methods", "GET,POST,OPTIONS")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_OPTIONS(self):
        self.reply(200, {})

    def do_POST(self):
        if urlparse(self.path).path == "/auth/v1/token":
            self.reply(200, {"access_token": "fake-isolated-token", "refresh_token": "fake-isolated-refresh",
                             "token_type": "bearer", "expires_in": 2_000_000_000,
                             "expires_at": 4_102_444_800, "user": USER})
        else:
            self.reply(405, {"detail": "Isolated verification rejects all product writes and AI calls"})

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/health":
            return self.reply(200, {"status": "isolated", "shared_database": False, "ai": False})
        if path == "/auth/v1/user":
            return self.reply(200, USER)
        if self.headers.get("Authorization") != "Bearer fake-isolated-token":
            return self.reply(401, {"detail": "Fake isolated session required"})
        if path == "/api/profile":
            return self.reply(200, PROFILE)
        if path == "/api/experiments":
            return self.reply(200, [])
        parts = path.split("/")
        if len(parts) >= 4 and parts[1:3] == ["api", "experiments"]:
            report = REPORTS.get(parts[3])
            if report:
                if len(parts) == 4:
                    return self.reply(200, report["experiment"])
                if parts[4] == "progress":
                    return self.reply(200, TIMELINES[parts[3]])
                if parts[4] == "report":
                    return self.reply(200, report)
                if parts[4] == "checkins":
                    return self.reply(200, [{
                        "id": f"00000000-0000-4000-8000-{point['day']:012d}", "experiment_id": parts[3],
                        "day_number": point["day"], "phase": point["phase"],
                        "intervention_completed": point["intervention_completed"],
                        "metric_values": point["values"], "note": point["note"],
                        "created_at": report["created_at"], "updated_at": report["created_at"],
                    } for point in report["chart"]["points"] if point["logged"]])
        self.reply(404, {"detail": "No isolated fixture for this route"})


if __name__ == "__main__":
    print("Isolated F4 API at http://127.0.0.1:8002; fake auth only; no shared DB or AI", flush=True)
    ThreadingHTTPServer(("127.0.0.1", 8002), Handler).serve_forever()
