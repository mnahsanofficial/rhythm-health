#!/usr/bin/env node
// Checks every agent log in .claude-logs/ against the 8x guide's format (docs/agent-logging-setup.md).
// scripts/check_log_format.py checks the exact format: file name, frontmatter keys and order, header block,
// entry markers and fields, and every recomputed value. This file adds who wrote the log and what's in it:
// a github_user that's unknown or doesn't match the author's email, a session_id that disagrees with the
// filename, and empty or agent-generated prompts.
// Old logs can't be edited, so a known problem in one is excused only by an entry in
// scripts/log-waivers.json naming the file, the checks excused and why.
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REQUIRED = [
  "session_id", "date", "author", "github_user", "git_email", "project",
  "session_status", "last_entry_type", "total_exchanges", "generated_at",
];

// Text an agent writes itself and sends as a user turn; never a person's prompt.
const GENERATED = [
  /^# Overview\s+Generate 0 to 3 hyperpersonalized suggestions/,
  /^The following is the Codex agent history/,
];

const FORMAT_CHECK = join(dirname(fileURLToPath(import.meta.url)), "check_log_format.py");

/** [check, message] pairs from the Python format check, which reuses the guide script's own functions. */
function formatProblems(name, text) {
  const run = spawnSync("python3", [FORMAT_CHECK], { input: JSON.stringify({ name, text }), encoding: "utf8", maxBuffer: 2 ** 28 });
  if (run.status !== 0) return [["format_check", `the format check couldn't run: ${run.error?.message ?? run.stderr}`]];
  return JSON.parse(run.stdout);
}

function frontmatter(text) {
  const match = /^---\n([\s\S]*?)\n---/.exec(text);
  if (!match) return null;
  return Object.fromEntries(
    match[1].split("\n").filter(line => line.includes(":")).map(line => {
      const at = line.indexOf(":");
      return [line.slice(0, at).trim(), line.slice(at + 1).trim()];
    }),
  );
}

function prompts(text) {
  const parts = text.split(/^\[CLAUDE_LOG_ENTRY (type=\w+) num=(\d+) session=[^\]]*\]$/m);
  const found = [];
  for (let i = 1; i < parts.length; i += 3) {
    if (parts[i] !== "type=PROMPT") continue;
    const lines = parts[i + 2].split("\n");
    let start = 1;
    while (start < lines.length && /^[a-z_]+: /.test(lines[start])) start += 1;
    found.push({ num: Number(parts[i + 1]), text: lines.slice(start).join("\n").trim() });
  }
  return found;
}

/** Problems with one log, as plain sentences. An empty list means it passes. */
export function checkLog(name, text, { authors, waivers, format = formatProblems }) {
  const excused = new Set(waivers[name]?.checks ?? []);
  const problems = [];
  const report = (check, message) => { if (!excused.has(check)) problems.push(`${name}: ${message}`); };

  for (const [check, message] of format(name, text)) report(check, message);

  const front = frontmatter(text);
  if (!front) return problems.length ? problems : [`${name}: no frontmatter`];
  for (const key of REQUIRED) {
    if (!front[key] && !excused.has("frontmatter")) problems.push(`${name}: missing frontmatter field ${key}`);
  }

  const session = name.replace(/\.md$/, "").split("_").slice(2).join("_");
  if (front.session_id && front.session_id !== session) {
    report("session_id", `session_id ${front.session_id} doesn't match the filename's ${session}`);
  }

  const email = front.git_email;
  const expected = authors[email];
  if (front.github_user === "unknown") {
    report("github_user", "github_user is unknown; the hook couldn't resolve the GitHub login");
  } else if (email && !expected) {
    report("github_user", `git_email ${email} isn't in scripts/log-authors.json`);
  } else if (expected && front.github_user && front.github_user !== expected) {
    report("github_user", `github_user ${front.github_user} doesn't match ${expected} for ${email}`);
  }

  const entries = prompts(text);
  if (entries.length === 0) report("empty_prompt", "no prompts");
  for (const { num, text: prompt } of entries) {
    if (!prompt) report("empty_prompt", `empty prompt #${num}`);
    else if (GENERATED.some(pattern => pattern.test(prompt))) report("generated_prompt", `prompt #${num} was generated by the agent, not typed by a person`);
  }
  return problems;
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const authors = JSON.parse(readFileSync(join(root, "scripts/log-authors.json"), "utf8"));
  const waivers = JSON.parse(readFileSync(join(root, "scripts/log-waivers.json"), "utf8"));
  const dir = join(root, ".claude-logs");
  const files = readdirSync(dir).filter(file => file.endsWith(".md")).sort();
  const problems = files.flatMap(file => checkLog(file, readFileSync(join(dir, file), "utf8"), { authors, waivers }));
  const stale = Object.keys(waivers).filter(file => !files.includes(file));
  for (const file of stale) problems.push(`${file}: listed in scripts/log-waivers.json but not in .claude-logs/`);

  if (problems.length) {
    console.error(`Agent logs: ${problems.length} problem(s)\n${problems.map(p => `  - ${p}`).join("\n")}`);
    process.exit(1);
  }
  console.log(`Agent logs: ${files.length} files pass (${Object.keys(waivers).length} older files have listed exceptions).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
